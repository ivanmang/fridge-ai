export type UiKey = keyof (typeof UI)["en"]

export function translate(locale: Locale, key: UiKey, vars: Record<string, string | number> = {}) {
  const text = UI[locale][key]
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""))
}

export function foodLabel(locale: Locale, name: string) {
  if (locale !== "zh") return name
  const shelf = findShelf(name)
  if (shelf && ZH_FOOD[shelf.name]) return ZH_FOOD[shelf.name]
  return name
}

export function cuisineLabel(locale: Locale, cuisine: string) {
  if (locale !== "zh") return cuisine
  return ZH_CUISINE[cuisine] ?? cuisine
}

export function placeLabel(locale: Locale, place: string) {
  if (locale !== "zh") return place
  if (place === "freezer") return UI.zh.placeFreezer
  if (place === "pantry") return UI.zh.placePantry
  return UI.zh.placeFridge
}

export function statusText(locale: Locale, status: ItemStatus) {
  return translate(locale, status)
}

export function whenText(locale: Locale, expires: string) {
  const n = daysUntil(expires)
  if (n === 0) return translate(locale, "whenToday")
  if (n === 1) return translate(locale, "whenTomorrow")
  if (n === -1) return translate(locale, "whenYesterday")
  if (n < 0) return translate(locale, "whenAgo", { n: -n })
  return translate(locale, "whenIn", { n })
}

export function recipeText(locale: Locale, recipe: Recipe) {
  if (locale !== "zh") return { name: recipe.name, cuisine: cuisineLabel(locale, recipe.cuisine), steps: recipe.steps }
  const zh = ZH_RECIPE[recipe.id]
  return {
    name: zh?.name ?? recipe.name,
    cuisine: cuisineLabel(locale, recipe.cuisine),
    steps: zh?.steps ?? recipe.steps,
  }
}
